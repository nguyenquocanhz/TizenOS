#ifndef TPK_FORMAT_H
#define TPK_FORMAT_H

// Cấu trúc định dạng TPK (Tizen Package)
// Một file TPK thực chất là một tập tin nén ZIP chứa các thành phần sau:
// - tizen-manifest.xml: Chứa thông tin về gói (ID, version, quyền hạn...)
// - signature1.xml: Chữ ký điện tử của tác giả/nhà phân phối
// - bin/: Thư mục chứa các tệp thực thi
// - lib/: Thư mục chứa các thư viện động (so)
// - res/: Thư mục chứa tài nguyên (hình ảnh, âm thanh, v.v.)

#endif // TPK_FORMAT_H
